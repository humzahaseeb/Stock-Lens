import { describe, it, expect } from 'vitest';
import { render, screen } from '@testing-library/react';
import NarrativeCard from '../components/NarrativeCard.jsx';

describe('NarrativeCard', () => {
  it('renders a filled-in narrative section with its source and date', () => {
    render(
      <NarrativeCard
        title="Business model"
        section={{ summary: 'Sells GPUs.', source: 'NVIDIA IR', asOf: '2026-11-01' }}
      />,
    );
    expect(screen.getByRole('heading', { name: 'Business model' })).toBeInTheDocument();
    expect(screen.getByText('Sells GPUs.')).toBeInTheDocument();
    expect(screen.getByText(/NVIDIA IR/)).toBeInTheDocument();
    expect(screen.getByText(/2026-11-01/)).toBeInTheDocument();
  });

  it('renders URL citations as secure external links', () => {
    render(
      <NarrativeCard
        title="Bear case"
        section={{
          points: ['Valuation risk.'],
          source: 'Google Finance — https://www.google.com/finance/quote/RR.:LON',
          asOf: '2026-11-09',
        }}
      />,
    );
    const citation = screen.getByRole('link', { name: 'Google Finance' });
    expect(citation).toHaveAttribute('href', 'https://www.google.com/finance/quote/RR.:LON');
    expect(citation).toHaveAttribute('target', '_blank');
    expect(citation).toHaveAttribute('rel', 'noreferrer');
  });

  it('shows a research-needed warning instead of fabricated data', () => {
    render(
      <NarrativeCard
        title="Analyst consensus"
        section={{ needsResearch: true, researchNote: 'Check a consensus source.' }}
      />,
    );
    expect(screen.getByRole('status')).toHaveTextContent('Check a consensus source.');
  });

  it('renders a list of bullet points', () => {
    render(<NarrativeCard title="Bull case" section={{ points: ['Point A', 'Point B'] }} />);
    expect(screen.getByText('Point A')).toBeInTheDocument();
    expect(screen.getByText('Point B')).toBeInTheDocument();
  });

  it('shows an auto-generated notice for data-derived bull/bear bullets', () => {
    render(
      <NarrativeCard
        title="Bull case"
        section={{ points: ['Strong margin.'], autoGenerated: true, note: 'Derived from data, not analyst commentary.' }}
      />,
    );
    expect(screen.getByRole('status')).toHaveTextContent('Derived from data, not analyst commentary.');
    expect(screen.getByText('Strong margin.')).toBeInTheDocument();
  });

  it('renders a live analyst consensus with breakdown, trend, and an unavailable price target', () => {
    render(
      <NarrativeCard
        title="Analyst consensus"
        section={{
          rating: 'Strong Buy',
          numberOfAnalysts: 30,
          breakdown: { strongBuy: 20, buy: 10, hold: 0, sell: 0, strongSell: 0 },
          trendDirection: 'improving',
          priceTarget12m: null,
          priceTargetNote: '12-month price target consensus is not available on any free-tier API.',
          source: 'Finnhub (analyst recommendation trends)',
          asOf: '2026-11-01',
        }}
      />,
    );
    expect(screen.getByText('Strong Buy', { selector: '.rating-pill' })).toBeInTheDocument();
    expect(screen.getByText('30 analysts')).toBeInTheDocument();
    expect(
      screen.getByText((_, element) => element?.tagName === 'P' && /has improving month-on-month/.test(element.textContent)),
    ).toBeInTheDocument();
    expect(screen.getByText('Not available')).toBeInTheDocument();
  });

  it('shows a source-pending notice for real content that still needs a citation', () => {
    render(
      <NarrativeCard
        title="Bull case"
        section={{
          points: ['Dominant AI architecture.'],
          needsResearch: false,
          sourcePending: true,
          aiDeclarationNote: 'Add the real source before submitting.',
        }}
      />,
    );
    expect(screen.getByText(/Add the real source before submitting\./)).toBeInTheDocument();
    expect(screen.getByText('Dominant AI architecture.')).toBeInTheDocument();
  });

  it('renders a fallback message when the section is missing entirely', () => {
    render(<NarrativeCard title="Bear case" section={null} />);
    expect(screen.getByText('Not available for this company.')).toBeInTheDocument();
  });
});
