import { describe, it, expect } from 'vitest';
import { deriveBullBear } from '../src/lib/deriveBullBear.js';

const strongFinancials = {
  financialHealth: {
    metrics: [
      { label: 'Net profit margin', value: '55%' },
      { label: 'Debt / Equity', value: '0.3' },
      { label: 'Current ratio', value: '4.1' },
    ],
  },
  valuation: { metrics: [{ label: 'P/E (TTM)', value: '45.2' }] },
};

describe('deriveBullBear', () => {
  it('generates bull points from strong margin/leverage/liquidity and bear points from high P/E', () => {
    const { bullCase, bearCase } = deriveBullBear(strongFinancials);
    expect(bullCase.autoGenerated).toBe(true);
    expect(bullCase.points.some((p) => p.includes('Net profit margin'))).toBe(true);
    expect(bullCase.points.some((p) => p.includes('Debt/Equity'))).toBe(true);
    expect(bullCase.points.some((p) => p.includes('Current ratio'))).toBe(true);
    expect(bearCase.autoGenerated).toBe(true);
    expect(bearCase.points.some((p) => p.includes('P/E'))).toBe(true);
  });

  it('includes analyst consensus rating and trend direction when provided', () => {
    const { bullCase, bearCase } = deriveBullBear({
      ...strongFinancials,
      consensus: { rating: 'Buy', numberOfAnalysts: 30, trendDirection: 'worsening', asOf: '2026-11-01' },
    });
    expect(bullCase.points.some((p) => p.includes('Buy'))).toBe(true);
    expect(bearCase.points.some((p) => p.includes('worsened'))).toBe(true);
  });

  it('includes insider sentiment when provided', () => {
    const { bullCase } = deriveBullBear({
      financialHealth: { metrics: [] },
      valuation: { metrics: [] },
      insiderSentiment: { mspr: 4.2, month: '2026-10', asOf: '2026-10' },
    });
    expect(bullCase.points.some((p) => p.includes('Insider sentiment'))).toBe(true);
  });

  it('returns null for a side when there is not enough data to say anything', () => {
    const { bullCase, bearCase } = deriveBullBear({
      financialHealth: { metrics: [] },
      valuation: { metrics: [] },
    });
    expect(bullCase).toBeNull();
    expect(bearCase).toBeNull();
  });

  it('flags weak margin and high leverage as bear points', () => {
    const { bearCase } = deriveBullBear({
      financialHealth: {
        metrics: [
          { label: 'Net profit margin', value: '2%' },
          { label: 'Debt / Equity', value: '2.5' },
          { label: 'Current ratio', value: '0.6' },
        ],
      },
      valuation: { metrics: [] },
    });
    expect(bearCase.points.some((p) => p.includes('thin'))).toBe(true);
    expect(bearCase.points.some((p) => p.includes('elevated'))).toBe(true);
    expect(bearCase.points.some((p) => p.includes('liquidity pressure'))).toBe(true);
  });
});
