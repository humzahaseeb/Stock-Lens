import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import request from 'supertest';
import { createApp } from '../src/app.js';
import { clearCache } from '../src/lib/cache.js';

const app = createApp();

describe('GET /api/health', () => {
  it('returns ok', async () => {
    const res = await request(app).get('/api/health');
    expect(res.status).toBe(200);
    expect(res.body).toEqual({ ok: true });
  });
});

describe('GET /api/company/:ticker', () => {
  beforeEach(() => {
    clearCache();
    delete process.env.FMP_API_KEY;
    delete process.env.FINNHUB_API_KEY;
    vi.restoreAllMocks();
  });
  afterEach(() => {
    vi.unstubAllGlobals();
  });

  it('rejects an invalid ticker', async () => {
    const res = await request(app).get('/api/company/not valid!');
    expect(res.status).toBe(400);
    expect(res.body.error).toMatch(/Invalid ticker/);
  });

  it('returns 404 for a ticker with no live data, seed cache, or overrides', async () => {
    const res = await request(app).get('/api/company/ZZZZ');
    expect(res.status).toBe(404);
  });

  it('falls back to overrides-only data when live FMP is unavailable (no API key)', async () => {
    const res = await request(app).get('/api/company/NVDA');
    expect(res.status).toBe(200);
    expect(res.body.ticker).toBe('NVDA');
    expect(res.body.financialsSource).toBe('unavailable');
    expect(res.body.consensusSource).toBe('manual-override');
    expect(res.body.businessModel.summary).toMatch(/GPU/i);
    // Bull/bear now has real, human-curated content (not the needsResearch placeholder).
    expect(res.body.bullCase.needsResearch).toBe(false);
    expect(res.body.bullCase.source).toBe('Yahoo Finance');
    expect(res.body.analystConsensus.needsResearch).toBe(false);
    expect(res.body.analystConsensus.numberOfAnalysts).toBe(34);
    expect(res.body.analystConsensus.breakdown.strongBuy).toBe(33);
    expect(res.body.analystConsensus.priceTarget12m).toBe(323.45);
    expect(res.body.analystConsensus.priceTargetHigh).toBe(465);
    expect(res.body.analystConsensus.priceTargetLow).toBe(275);
    expect(res.body.analystConsensus.currentPrice).toBe(178.3);
    expect(res.body.incomeStatements.annual.demoData).toBe(true);
    expect(res.body.incomeStatements.quarterly.data).toHaveLength(4);
    expect(res.body.financialHealthSource).toBe('demo-data');
    expect(res.body.financialHealth.demoData).toBe(true);
    expect(res.body.valuationSource).toBe('demo-data');
    expect(res.body.valuation.demoData).toBe(true);
    expect(res.body.disclaimer).toMatch(/not financial advice/i);
  });

  it('prefers real, human-curated override bull/bear content over auto-derived bullets', async () => {
    process.env.FMP_API_KEY = 'test-key';
    vi.stubGlobal(
      'fetch',
      vi.fn(async (url) => {
        if (url.includes('/profile/'))
          return {
            ok: true,
            json: async () => [{ companyName: 'NVIDIA Corporation', ceo: 'Jensen Huang', currency: 'USD' }],
          };
        if (url.includes('/quote/')) return { ok: true, json: async () => [{ price: 120, pe: 45, eps: 2.6, marketCap: 3e12 }] };
        if (url.includes('/ratios/')) return { ok: true, json: async () => [{ netProfitMargin: 0.5, debtEquityRatio: 0.3, currentRatio: 4 }] };
        throw new Error(`unexpected ${url}`);
      }),
    );

    const res = await request(app).get('/api/company/NVDA');
    expect(res.status).toBe(200);
    expect(res.body.financialsSource).toBe('live');
    expect(res.body.valuation.metrics.length).toBeGreaterThan(0);
    expect(res.body.businessModel.summary).toMatch(/GPU/i);
    expect(res.body.ceo).toBe('Jensen Huang');
    expect(res.body.marketCap).toBe('4.30T');
    expect(res.body.marketCapCurrency).toBe('USD');
    expect(res.body.peRatio).toBe('22.54');
    expect(res.body.eps).toBe('$7.91');
    expect(res.body.quarterlyDividend).toBe('$0.25');
    expect(res.body.financialHealthSource).toBe('demo-data');
    expect(res.body.financialHealth.metrics.find((metric) => metric.label === 'Free cash flow (TTM)').value).toBe(
      'USD 110B',
    );
    expect(res.body.valuationSource).toBe('demo-data');
    expect(res.body.marketCapSource).toBe('Synthetic demo data');
    expect(res.body.valuation.metrics.find((metric) => metric.label === 'Forward P/E').value).toBe('19.8');
    expect(res.body.valuation.metrics.find((metric) => metric.label === 'EV / EBITDA').value).toBe('21.3');
    expect(res.body.valuation.metrics.find((metric) => metric.label === 'Quarterly dividend').value).toBe('$0.25');
    expect(res.body.incomeStatements.annual.demoData).toBe(true);
    expect(res.body.incomeStatements.annual.data[0].fiscalYear).toBe('2022');
    // Real metrics were present (which would normally auto-derive bull/bear),
    // but NVDA's override has real human content, so that wins instead.
    expect(res.body.bullCase.autoGenerated).toBeUndefined();
    expect(res.body.bullCase.points.some((p) => p.includes('CUDA'))).toBe(true);
  });

  it('auto-derives bull/bear from live data when no human narrative override exists (AAPL)', async () => {
    process.env.FMP_API_KEY = 'test-key';
    vi.stubGlobal(
      'fetch',
      vi.fn(async (url) => {
        if (url.includes('/profile/')) return { ok: true, json: async () => [{ companyName: 'Apple Inc.' }] };
        if (url.includes('/quote/')) return { ok: true, json: async () => [{ price: 10, pe: 45, eps: 0.2, marketCap: 5e10 }] };
        if (url.includes('/ratios/')) return { ok: true, json: async () => [{ netProfitMargin: 0.5, debtEquityRatio: 0.3, currentRatio: 4 }] };
        throw new Error(`unexpected ${url}`);
      }),
    );

    const res = await request(app).get('/api/company/AAPL');
    expect(res.status).toBe(200);
    expect(res.body.bullCase.autoGenerated).toBe(true);
    expect(res.body.bearCase.autoGenerated).toBe(true);
    expect(res.body.bullCase.points.some((point) => /analyst consensus/i.test(point))).toBe(false);
    expect(res.body.valuation.note).toMatch(/Forward P\/E and EV \/ EBITDA unavailable/);
  });

  it('uses a live Finnhub analyst consensus rating when FINNHUB_API_KEY is set', async () => {
    process.env.FINNHUB_API_KEY = 'test-finnhub-key';
    process.env.FMP_API_KEY = 'test-fmp-key';
    vi.stubGlobal(
      'fetch',
      vi.fn(async (url) => {
        if (url.includes('/stock/recommendation'))
          return {
            ok: true,
            json: async () => [{ symbol: 'AAPL', period: '2026-11-01', strongBuy: 20, buy: 10, hold: 0, sell: 0, strongSell: 0 }],
          };
        if (url.includes('/stock/insider-sentiment')) return { ok: true, json: async () => ({ data: [] }) };
        if (url.includes('/profile/')) return { ok: true, json: async () => [{ companyName: 'Apple Inc.', currency: 'USD' }] };
        if (url.includes('/quote/'))
          return { ok: true, json: async () => [{ price: 180, pe: 30, forwardPE: 25.2, eps: 6, marketCap: 2e12 }] };
        if (url.includes('/ratios/'))
          return {
            ok: true,
            json: async () => [{ netProfitMargin: 0.25, debtEquityRatio: 1, currentRatio: 1, enterpriseValueMultiple: 18.4 }],
          };
        if (url.includes('/cash-flow-statement/'))
          return {
            ok: true,
            json: async () => [
              { date: '2026-09-30', freeCashFlow: 1300000000, reportedCurrency: 'USD' },
              { date: '2026-06-30', freeCashFlow: 1200000000, reportedCurrency: 'USD' },
              { date: '2026-03-31', freeCashFlow: 1100000000, reportedCurrency: 'USD' },
              { date: '2025-12-31', freeCashFlow: 1000000000, reportedCurrency: 'USD' },
            ],
          };
        if (url.includes('/income-statement/')) {
          const annual = url.includes('period=annual');
          return {
            ok: true,
            json: async () => [
              {
                date: annual ? '2025-01-26' : '2026-07-26',
                calendarYear: annual ? '2025' : '2026',
                period: annual ? 'FY' : 'Q2',
                revenue: 100,
                netIncome: 50,
                reportedCurrency: 'USD',
              },
            ],
          };
        }
        throw new Error(`unexpected ${url}`);
      }),
    );

    const res = await request(app).get('/api/company/AAPL');
    expect(res.status).toBe(200);
    expect(res.body.consensusSource).toBe('live');
    expect(res.body.analystConsensus.rating).toBe('Strong Buy');
    expect(res.body.analystConsensus.source).toBe('Finnhub (analyst recommendation trends)');
    expect(res.body.analystConsensus.priceTarget12m).toBeNull();
    expect(res.body.valuationSource).toBe('live');
    expect(res.body.incomeStatements.annual.data[0].fiscalYear).toBe('2025');
    expect(res.body.incomeStatements.quarterly.data[0].period).toBe('Q2');
    expect(res.body.financialHealthSource).toBe('live');
    expect(res.body.financialHealth.metrics.find((metric) => metric.label === 'Free cash flow (TTM)').value).toBe(
      'USD 4.6B',
    );
    expect(res.body.valuation.metrics.find((metric) => metric.label === 'Forward P/E').value).toBe('25.2');
    expect(res.body.valuation.metrics.find((metric) => metric.label === 'EV / EBITDA').value).toBe('18.4');
    delete process.env.FINNHUB_API_KEY;
    delete process.env.FMP_API_KEY;
  });

  it('prefers the curated NVIDIA screenshot consensus over live Finnhub counts', async () => {
    process.env.FINNHUB_API_KEY = 'test-finnhub-key';
    vi.stubGlobal(
      'fetch',
      vi.fn(async (url) => {
        if (url.includes('/stock/recommendation'))
          return {
            ok: true,
            json: async () => [{ symbol: 'NVDA', period: '2026-11-01', strongBuy: 10, buy: 5, hold: 2, sell: 1, strongSell: 0 }],
          };
        if (url.includes('/stock/insider-sentiment')) return { ok: true, json: async () => ({ data: [] }) };
        throw new Error(`unexpected ${url}`);
      }),
    );

    const res = await request(app).get('/api/company/NVDA');
    expect(res.status).toBe(200);
    expect(res.body.consensusSource).toBe('manual-override');
    expect(res.body.analystConsensus.numberOfAnalysts).toBe(34);
    expect(res.body.analystConsensus.priceTarget12m).toBe(323.45);
    delete process.env.FINNHUB_API_KEY;
  });

  it('returns Rolls-Royce overrides for ticker RR.L', async () => {
    const res = await request(app).get('/api/company/RR.L');
    expect(res.status).toBe(200);
    expect(res.body.name).toBe('Rolls-Royce Holdings plc');
    expect(res.body.businessModel.summary).toMatch(/engines/i);
    expect(res.body.consensusSource).toBe('demo-data');
    expect(res.body.analystConsensus.needsResearch).toBe(false);
    expect(res.body.analystConsensus.demoData).toBe(true);
    expect(res.body.analystConsensus.numberOfAnalysts).toBe(24);
    expect(res.body.analystConsensus.currentPrice).toBe(15.17);
    expect(res.body.analystConsensus.priceTarget12m).toBe(18.2);
    expect(res.body.incomeStatements.annual.demoData).toBe(true);
    expect(res.body.incomeStatements.annual.data).toHaveLength(5);
    expect(res.body.incomeStatements.quarterly.data).toHaveLength(4);
    expect(res.body.financialHealthSource).toBe('demo-data');
    expect(res.body.financialHealth.demoData).toBe(true);
    expect(res.body.valuationSource).toBe('demo-data');
    expect(res.body.valuation.demoData).toBe(true);
    expect(res.body.valuation.metrics.find((metric) => metric.label === 'Forward P/E').value).toBe('29.8');
    expect(res.body.valuation.metrics.find((metric) => metric.label === 'EV / EBITDA').value).toBe('16.4');
    expect(res.body.valuation.metrics.find((metric) => metric.label === 'Quarterly dividend').value).toBe('£0.05');
  });
});
